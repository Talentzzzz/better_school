-- comment-like-count-cutover.sql —— 评论点赞计数切窄表 + post_comment.like_count 删列
-- （comment-count-narrow-table 票 04；本 effort 的不可逆点）
--
-- 何时执行：只针对**存量（线上）库**。开发库 / 测试库不需要跑——两库由 init-*.sql + schema.sql 重建，
--   schema.sql 已按删列后的形状建表（本脚本针对的是还带着旧列、尚未删列的存量库）。
--
-- 执行序（四步缺一不可，本文件只承担第 ④ 步）：
--   ① 建 post_comment_like_count（计数真源窄表）——执行 schema.sql 该表的 DDL
--      （`CREATE TABLE IF NOT EXISTS post_comment_like_count ...`）。本脚本不复制 DDL：唯一来源仍是
--      schema.sql（同 market-feed-uv-backfill.sql 的口径），照那节原样执行即可。
--   ② 建 post_comment_feed_index（根评论热评排序投影）——同上，schema.sql 该表的 DDL。
--   ③ 起新 jar —— 读窄表 + 过审造窄表行与索引行 + 点赞旁带索引 ±N。**前提是 ①② 两表已在**：
--      新代码的审核通过与点赞事务直接写这两张表，表不在则审核 / 点赞整条链路失败。
--   ④ 本文件：删 post_comment.like_count —— 只能在 ③ 之后跑。此时计数读窄表、热评排序读索引，
--      旧列既无写方也无读方，删它才不打断任何链路。
--
-- 前置确认（执行前人工核对，两条都过才动手）：
--   新 jar 已接管：本 effort 之前的那个 jar 只认主列、压根不写这两张表，所以「这两张表有活写入」
--   就是新 jar 在跑的证明——
--     SELECT COUNT(*), MAX(update_time) FROM post_comment_like_count;   -- 计数行在涨、update_time 接近当前
--     SELECT COUNT(*), MAX(update_time) FROM post_comment_feed_index;   -- 同上（只含根评论）
--   旧列无写方：值域冻结（不要求为 0/NULL），观察口径同 feed-index-uv / market-feed-uv 两份删列脚本——
--   隔一段时间跑两次，数字不再增长：
--     SELECT COUNT(*) FROM post_comment WHERE like_count > 0;
--
-- 不管存量（用户已确认接受，本 effort 不做任何搬数）：
--   - 不回填、不搬历史点赞。旧列里已有的数值随删列一并丢弃。
--   - 后果：存量评论在窄表里没有行，展示口径按「窄表缺行 = 0」显示 **0**——点赞关系明细
--     post_comment_like 仍原样在库，但没有把它折成计数的脚本。
--   - 索引表同样从空表起步（本 effort 不做首建重建）。所以「最热」档在存量帖上暂时只能看到切码后
--     过审的根评论；运营若要把存量可见根评论补进索引，跑一次 commentFeedIndexRebuildJob（票 03）。
--     补齐的行 like_count 按窄表抄 = 0，热评序对这些行退化成按 comment_id 升序（历史点赞不参与排序）。
--   - 若确实要「历史热评」/ 历史点赞数，唯一办法是重放 post_comment_like 明细重新计数（本 effort 不做）。
--
-- 回滚口径：
--   - 不可逆点就是第 ④ 步（删列）。**删列前**回滚到本 effort 之前的线上 jar 无害：那版代码只认旧列、
--     不读也不写两张新表（新表多余，放着不动即可）。
--   - **删列后**不能再回滚到那版 jar：它在四条读语句（根列表两档 / 楼内平铺 / 作者主页 tab / 单条）
--     和计数 UPDATE 里都写着 like_count，回滚会立刻撞 Unknown column 'like_count'。必须先手工反向 DDL：
--       ALTER TABLE post_comment ADD COLUMN like_count INT NOT NULL DEFAULT 0;
--     且加回来的是一列**全 0 空列**：历史点赞数已随删列丢弃，不会回来（关系明细还在，但没人再折它）。
--   - 本 effort 单 PR 交付、中间的票 01/02/03 不单独发版：线上只存在「effort 之前」与「effort 之后」
--     两版 jar，上面说的旧 jar 就是前者。
--
-- 不幂等：MySQL 8.0 的 ALTER TABLE 不支持 DROP COLUMN IF EXISTS，二次执行会报 1091（列不存在）。
--   报错即目标已达成，无需处理。
-- 执行方式（不自带 USE，库名在命令行给；在前面三步做完之后再跑）：
--   docker exec -i bs-mysql mysql -uroot -pbs123456 --default-character-set=utf8mb4 better_school < backend/better-school/sql/backfill/comment-like-count-cutover.sql
